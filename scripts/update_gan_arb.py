def main():
    with open(BASE_ZH, "r", encoding="utf-8") as f:
        zh_data = json.load(f)

    with open(GAN_FILE, "r", encoding="utf-8") as f:
        gan_data = json.load(f)

    # 1. Apply fixes
    for k, v in FIXES.items():
        gan_data[k] = v

    # 2. Apply new translations
    for k, v in NEW_TRANSLATIONS.items():
        gan_data[k] = v

    # 3. Ensure protected keys strictly intact
    for k, v in PROTECTED_KEYS.items():
        gan_data[k] = v

    # 4. Verify all placeholders match
    ph_re = re.compile(r"\{[a-zA-Z0-9_]+\}")
    placeholder_errors = []
    for k, zv in zh_data.items():
        if k.startswith("@"):
            continue
        gv = gan_data.get(k)
        if gv is None:
            placeholder_errors.append(f"Missing key in gan: {k}")
            continue
        zh_phs = sorted(ph_re.findall(zv))
        gan_phs = sorted(ph_re.findall(gv))
        if zh_phs != gan_phs:
            placeholder_errors.append(f"Placeholder mismatch for {k}: zh={zh_phs}, gan={gan_phs}")

    if placeholder_errors:
        print("ERROR: Placeholder validation failed:")
        for err in placeholder_errors:
            print("  ", err)
        sys.exit(1)

    # 5. Write back to GAN_FILE preserving formatting
    with open(GAN_FILE, "w", encoding="utf-8") as f:
        json.dump(gan_data, f, ensure_ascii=False, indent=2)
        f.write("\n")

    print(f"Successfully updated {GAN_FILE}")


if __name__ == "__main__":
    main()
