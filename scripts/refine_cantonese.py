def build_cantonese_arb():
    cc = opencc.OpenCC("t2s")
    with open(BASE_ZH, "r", encoding="utf-8") as f:
        zh_data = json.load(f)

    # Load current app_yue.arb to retain existing good translations
    existing_yue = {}
    if YUE_ARB.exists():
        with open(YUE_ARB, "r", encoding="utf-8") as f:
            existing_yue = json.load(f)

    ph_re = re.compile(r"\{[a-zA-Z0-9_]+\}")

    output = {}
    for key, zh_val in zh_data.items():
        if key == "@@locale":
            output["@@locale"] = "yue"
            continue
        if key.startswith("@"):
            # Metadata item: copy from zh_data
            output[key] = zh_val
            continue

        # Translation key
        if key in STRICT_TEST_KEYS:
            res = STRICT_TEST_KEYS[key]
        elif key in YUE_MAP:
            res = YUE_MAP[key]
        elif key in existing_yue and existing_yue[key] != zh_val:
            # Existing dialect translation that was already customized
            res = existing_yue[key]
        else:
            # Fallback to existing or zh_val
            res = existing_yue.get(key, zh_val)

        # Convert to simplified Chinese (guarantee no traditional chars)
        res_s = cc.convert(res)

        # Verify placeholders
        zh_phs = set(ph_re.findall(zh_val)) if isinstance(zh_val, str) else set()
        res_phs = set(ph_re.findall(res_s)) if isinstance(res_s, str) else set()
        if zh_phs != res_phs:
            print(f"WARNING: Placeholder mismatch in {key}: zh={zh_phs}, yue={res_phs}")
            # Fix if needed
            res_s = zh_val

        output[key] = res_s

    # Write output
    with open(YUE_ARB, "w", encoding="utf-8") as f:
        json.dump(output, f, ensure_ascii=False, indent=2)
        f.write("\n")

    print(f"Wrote {len(output)} keys to {YUE_ARB}")


if __name__ == "__main__":
    build_cantonese_arb()
