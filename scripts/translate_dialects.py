def update_hsn():
    path = Path("lib/l10n/app_hsn.arb")
    with open(path, "r", encoding="utf-8") as f:
        data = json.load(f)
    for k, v in ZH_DATA.items():
        if k not in data:
            data[k] = v
    for k, v in HSN_TRANSLATIONS.items():
        if k in data:
            data[k] = v
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    print("Updated app_hsn.arb with 1067 keys and Changsha translations.")


